import uuid
from datetime import datetime

from sqlalchemy import BigInteger, DateTime, Text, func
from sqlalchemy.orm import Mapped, mapped_column

from app.core.db import Base


class ImageRow(Base):
    """One row per stored image: metadata plus where the bytes live. The bytes themselves are in ImageStorage.

    Deliberately minimal. Things we'd likely add later, and why:
      - sha256 (indexed, non-unique): strong ETag / conditional GETs, and de-duplicating identical uploads.
      - width / height: thumbnails and other variants without re-decoding the original.
      - storage_backend: keep old rows readable after switching between local and S3.
      - deleted_at: soft delete once a DELETE endpoint exists.
      - owner_id: once the shared Basic-auth credential is replaced by real per-caller identity.
    """

    __tablename__ = "images"

    id: Mapped[uuid.UUID] = mapped_column(primary_key=True)  # uuid7, generated by the app
    # Sanitised client-supplied name, informational only. Never used to address the blob.
    original_filename: Mapped[str | None] = mapped_column(Text)
    storage_key: Mapped[str] = mapped_column(Text)  # where the blob lives in ImageStorage: `<id>.<extension>`
    content_type: Mapped[str] = mapped_column(Text)
    size_bytes: Mapped[int] = mapped_column(BigInteger)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
